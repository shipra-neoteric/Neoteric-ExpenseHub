import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import { paiseToInr } from './format';

// House PDF style per UI_STYLE_GUIDE.md section 20: fixed corporate navy
// (not the dynamic per-company theme color), Rs. prefix (the ₹ glyph isn't
// reliable in the default PDF font), filename `{id}.pdf`.
const NAVY = [26, 54, 93];

const IMAGE_MIME = new Set(['image/jpeg', 'image/png', 'image/webp']);

async function urlToDataUrl(url) {
  const res = await fetch(url, { mode: 'cors' });
  if (!res.ok) throw new Error(`Failed to fetch ${url}`);
  const blob = await res.blob();
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onloadend = () => resolve(reader.result);
    reader.onerror = reject;
    reader.readAsDataURL(blob);
  });
}

export async function exportSiteExpensesPdf({ expenses, totals, bySite = [], filters, generatedBy, appTimezone = 'Asia/Kolkata', includeReceipts = false }) {
  const doc = new jsPDF();

  doc.setFillColor(...NAVY);
  doc.rect(0, 0, 210, 22, 'F');
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(14);
  doc.text('Neoteric Properties — Site Expenses Report', 10, 10);
  doc.setFontSize(9);
  doc.text(`Generated: ${new Date().toLocaleString('en-IN', { timeZone: appTimezone })} (${appTimezone})`, 10, 17);

  doc.setTextColor(30, 30, 30);
  doc.setFontSize(9);
  let y = 28;
  doc.text(`Sites: ${filters.siteNames?.join(', ') || 'All accessible'}`, 10, y);
  y += 5;
  doc.text(`Filters: ${filters.summary || 'None'}`, 10, y);
  y += 5;
  doc.text(`Generated by: ${generatedBy}`, 10, y);
  y += 8;

  doc.setFillColor(...NAVY);
  doc.rect(10, y, 190, 8, 'F');
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(10);
  doc.text('Summary', 12, y + 5.5);
  y += 12;

  doc.setTextColor(30, 30, 30);
  doc.setFontSize(9);
  doc.text(`Approved Spend: Rs. ${paiseToInr(totals.approvedSpend, { withSymbol: false })}`, 12, y);
  y += 5;
  doc.text(`Pending Amount: Rs. ${paiseToInr(totals.pendingAmount, { withSymbol: false })}`, 12, y);
  y += 7;

  Object.entries(totals.categoryWise || {}).forEach(([cat, amt]) => {
    doc.text(`${cat}: Rs. ${paiseToInr(amt, { withSymbol: false })}`, 12, y);
    y += 5;
  });
  y += 3;

  if (bySite.length > 1) {
    doc.setFillColor(...NAVY);
    doc.rect(10, y, 190, 8, 'F');
    doc.setTextColor(255, 255, 255);
    doc.setFontSize(10);
    doc.text('Site-wise Summary', 12, y + 5.5);
    y += 12;

    doc.setTextColor(30, 30, 30);
    doc.setFontSize(9);
    bySite.forEach((s) => {
      doc.text(
        `${s.siteName}: Approved Rs. ${paiseToInr(s.approvedSpend, { withSymbol: false })} | Pending Rs. ${paiseToInr(s.pendingAmount, { withSymbol: false })} | ${s.count} expense(s)`,
        12,
        y
      );
      y += 5;
    });
    y += 3;
  }

  const rows = expenses.map((e) => [
    e.expenseNumber,
    e.siteId?.name || '',
    new Date(e.expenseDate).toLocaleDateString('en-IN'),
    e.categorySnapshot?.name || '',
    e.description,
    `Rs. ${paiseToInr(e.amountPaise, { withSymbol: false })}`,
    e.paymentMode,
    e.status,
  ]);

  autoTable(doc, {
    startY: y,
    head: [['Number', 'Site', 'Date', 'Category', 'Description', 'Amount', 'Mode', 'Status']],
    body: rows,
    headStyles: { fillColor: NAVY, textColor: 255 },
    styles: { fontSize: 8 },
    theme: 'grid',
  });

  if (includeReceipts) {
    const withReceipts = expenses.filter((e) => e.attachments?.length);
    for (const e of withReceipts) {
      for (const att of e.attachments) {
        doc.addPage();
        doc.setFontSize(11);
        doc.setTextColor(30, 30, 30);
        doc.text(`Receipt — ${e.expenseNumber} (${att.originalName})`, 10, 12);
        if (IMAGE_MIME.has(att.mimeType)) {
          try {
            const dataUrl = await urlToDataUrl(att.url);
            const format = att.mimeType === 'image/png' ? 'PNG' : 'JPEG';
            doc.addImage(dataUrl, format, 10, 18, 190, 0);
          } catch (err) {
            doc.setFontSize(9);
            doc.text(`Could not load image. Open directly: ${att.url}`, 10, 25);
          }
        } else {
          doc.setFontSize(9);
          doc.text(`This file type (${att.mimeType}) can't be embedded. Open directly:`, 10, 22);
          doc.setTextColor(30, 60, 150);
          doc.textWithLink(att.url, 10, 28, { url: att.url });
        }
      }
    }
  }

  doc.save('site-expenses-report.pdf');
}
